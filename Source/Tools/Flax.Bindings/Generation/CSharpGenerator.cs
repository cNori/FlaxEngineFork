    static string Id(string name) => CSharpKeywords.Contains(name) ? "@" + name : name;
    static bool Identifier(string? name) => !string.IsNullOrEmpty(name) && (char.IsLetter(name[0]) || name[0] == '_') && name.All(c => char.IsLetterOrDigit(c) || c == '_');
    static string Comment(string text) => text.Replace("\r", " ").Replace("\n", " ");
    void Error(DeclarationDescriptor declaration, string message)
    {
        var where = declaration.Name;
        if (string.IsNullOrEmpty(where.text)) where = declaration.HeaderTokens.FirstOrDefault(t => !t.IsTrivia);
        result.Diagnostics.Add(new LogEntry(message, where, LogEntryType.Error, "VETCS001", declaration.DiagnosticFile?.Path));
    }
