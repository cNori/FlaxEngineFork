using System.Text;
using System.Text.RegularExpressions;
using VETools.Text;
using static VETools.Tokenizer;

namespace VETools.Generation;

internal sealed class CSharpGenerationResult
{
    public string Source = "";
    public List<LogEntry> Diagnostics = [];
    public List<LogEntry> Notes = [];
    public List<string> NativeInjectedCode = [];
    public HashSet<string> SharedManagedDeclarations = new(StringComparer.Ordinal);
    public HashSet<string> RequiredManagedDeclarations = new(StringComparer.Ordinal);
    public IReadOnlySet<ClassDescriptor> ProjectClassLifetimes = new HashSet<ClassDescriptor>();
    public bool Success => !Diagnostics.Any(entry => entry.BlocksGeneration);
    public EmittedBindingManifest Bindings { get; } = new();
}

// Declaration preview only. A separate interop backend must validate ABI layout,
// ownership and lifetimes before emitting callable native wrappers.
internal sealed class CSharpGenerator
{
    sealed record EmittedSignature(FunctionDescriptor Native, string Managed, IReadOnlyList<string> ParameterTypes);
    readonly CSharpGenerationResult result = new();
    readonly StringBuilder output = new();
    readonly NativeLayout layout = new();
    readonly Stack<NativeStructLayout?> storageScopes = new();
    readonly HashSet<TypeSymbol> emittedOpaqueTypes = [];
    ExportPlan plan = null!;
    IReadOnlyDictionary<string, DeclarationMacroKind> declarationMacros = new Dictionary<string, DeclarationMacroKind>();
    List<Token> sourceTokens = [];
    int indent;
    CSharpGenerator() { }

    public static CSharpGenerationResult Generate(FileDescriptor file, string abi, ExportPlan? emissionPlan = null, bool separateSharedDeclarations = false)
    {
        var generator = new CSharpGenerator();
        generator.sourceTokens = file.Tokens;
        generator.declarationMacros = file.Converters.DeclarationMacros;
        generator.result.ProjectClassLifetimes = file.ProjectClassLifetimes;
        generator.result.NativeInjectedCode.AddRange(TemplateInstantiationPass.Declarations(file)
            .SelectMany(d => d.Api.InjectedCode).Where(c => c.Language == "cpp").Select(c => c.Code));
        if (file.TypeInfos == null) TypeInfoPass.Run(file);
        AutomaticFieldConverters.Apply(file);
        StandardConverters.Apply(file);
        MarshalAsConverters.Apply(file);
        generator.plan = emissionPlan ?? ExportPlan.Build(file);
        generator.result.Diagnostics.AddRange(generator.plan.Errors);
        generator.result.Notes.AddRange(generator.plan.Warnings);
        var bindings = BindingSignaturePass.Run(file, generator.plan.Validates);
        generator.result.Diagnostics.AddRange(bindings.Diagnostics);
        generator.result.Diagnostics.AddRange(CSharpNameValidator.Validate(file, generator.plan));
        if (!generator.result.Success) return generator.result;
        if (file.Errors.Any(entry => entry.IsError))
            generator.Error(file, "Cannot generate from a file with first-pass errors.");
        if (abi != "windows-x64") generator.Error(file, "Select the currently supported ABI explicitly: windows-x64 (MSVC default signed char).");
        generator.layout.DefaultPackingKnown = !Regex.IsMatch(file.SourceText, @"(?m)^\s*#\s*pragma\s+pack\b");
        generator.Line("// <auto-generated />");
        generator.Line("// Input: " + Comment(file.Path ?? "<in-memory>"));
        generator.Line("// Export policy: only [[Export]] declarations; native accessor dependencies use private wrappers.");
        generator.Line("// Declaration preview only: no native calls, marshalling or ABI layout guarantees.");
        generator.Line("// Method bodies throw; C++ initializers and function implementations are not translated.");
        generator.Line("// Planned native-call policy: in copies to a temporary, out copies back, ref shares storage.");
        generator.Line("// Explicit offsets/sizes do not guarantee over-aligned managed addresses.");
        generator.Line("#nullable disable");
        generator.Line("#pragma warning disable CS0169, CS0649, CS0628");
        generator.Line("using global::System;");
        generator.Line("using global::System.ComponentModel;");
        generator.Line("using global::System.Runtime.InteropServices;");
        foreach (string ns in file.Converters.ManagedUsings.Order(StringComparer.Ordinal)) generator.Line("using global::" + ns + ";");
        if (file.Converters.DefaultManagedNamespace != null && TemplateInstantiationPass.Declarations(file).Any(d => d.Api.ManagedAttributes.Any(a => a.Contains("JsonProperty(")))) generator.Line("using global::Newtonsoft.Json;");
        generator.Injected(file);
        foreach (var group in generator.plan.Members(file).GroupBy(HandleNetCS.NamespaceKey))
        {
            bool namespaced = group.Key.Length != 0;
            if (namespaced) { generator.Line("namespace " + Qualified(group.Key)); generator.Open(); }
            var names = new HashSet<string>(StringComparer.Ordinal);
            foreach (var alias in group.OfType<AliasDescriptor>()) generator.Alias(alias);
            foreach (var declaration in group)
            {
                if (declaration is not (TypeDescriptor or EnumDescriptor)) continue;
                if (IsForward(declaration)) { generator.Forward(declaration, false); continue; }
                if (!names.Add(declaration.Name.text)) generator.Error(declaration, "Duplicate generated type name.");
                generator.Declaration(declaration, false);
            }
            var globals = group.Where(d => d is FieldDescriptor or FunctionDescriptor).ToList();
            if (globals.Count > 0)
            {
                if (!names.Add("NativeGlobals")) generator.Error(globals[0], "NativeGlobals conflicts with a native type name.");
                generator.Documentation(Array.Empty<Token>());
                generator.Line("public static partial class NativeGlobals"); generator.Open();
                generator.Members(globals, false, false, true);
                generator.Close();
            }
            foreach (var raw in group.OfType<RawDeclarationDescriptor>())
                generator.Error(raw, "Raw declaration needs an explicit generation handler.");
            if (namespaced) generator.Close();
        }
        foreach (var support in generator.result.Bindings.Entries.SelectMany(entry =>
            (entry.NativeType == null ? Enumerable.Empty<VETools.Text.TypeInfo>() : [entry.NativeType])
                .Concat(entry.Parameters?.Select(p => p.NativeType) ?? []))
            .SelectMany(AutomaticFieldConverters.Converters).Concat(EventInterop.CopiedConverters(generator.result.Bindings.Entries)).SelectMany(c => c.ManagedDeclarations).Concat(generator.result.RequiredManagedDeclarations).Distinct(StringComparer.Ordinal))
            if (separateSharedDeclarations) generator.result.SharedManagedDeclarations.Add(support);
            else generator.output.AppendLine(support);
        generator.result.Source = generator.output.ToString();
        if (!generator.result.Success) generator.result.Bindings.Clear();
        return generator.result;
    }

    void Alias(AliasDescriptor alias)
    {
        if (alias.TemplateParameters.Count != 0)
        { Note(alias, $"Alias template '{alias.QualifiedName}' is retained for concrete type substitution; no open managed alias is emitted."); return; }
        if (alias.TypeInfo is NamedTypeInfo { Specialization.Concrete: { } concrete })
        { Note(alias, $"Concrete typedef '{alias.QualifiedName}' maps to '{concrete.QualifiedName}' ({concrete.NativeQualifiedName}); equivalent aliases share one specialization."); return; }
        if (alias.TypeInfo is NamedTypeInfo { Resolution: TypeResolution.Builtin } or NamedTypeInfo { Converter.IsAlias: true } || alias.Api.Alias)
        { Note(alias, $"Exported transparent typedef '{alias.QualifiedName}' resolves to '{alias.TypeInfo?.Display}'; C# uses the underlying type."); return; }
        if (alias.TypeInfo is NamedTypeInfo { Specialization: { } } specialization)
            Error(alias, $"Resolved exported typedef '{alias.QualifiedName}' as '{specialization.Display}'. Concrete specialization emission is required before declaring its managed type; union-backed fields require native accessors, not guessed managed storage.");
        else Error(alias, $"Exported typedef '{alias.QualifiedName}' targets '{alias.TypeInfo?.Display ?? "unknown"}'. A concrete alias/type emission handler is required.");
    }

    void Declaration(DeclarationDescriptor declaration, bool nested)
    {
        if (declaration is EnumDescriptor enumeration) { Enum(enumeration, nested); return; }
        if (!Identifier(declaration.Name.text)) { Error(declaration, "Anonymous or invalid type name cannot be emitted."); return; }
        if (declaration is not TypeDescriptor type) return;
        if (type.Api.InBuild) return;
        if (type.CanonicalManagedValue || type.SourceFile?.Converters.ManagedValuePartial(type.QualifiedName) != null)
        {
            if (type.AutomaticValueConverter is { } valueConverter) result.RequiredManagedDeclarations.UnionWith(valueConverter.ManagedDeclarations);
            else Error(type, "No converter for the registered managed value partial '" + type.QualifiedName + "'.");
            var nestedEnums = plan.Members(type).OfType<EnumDescriptor>().ToArray();
            bool knownPartial = type.SourceFile?.Converters.ManagedValuePartial(type.QualifiedName) != null;
            bool nativeDefault = CanEmitNativeDefault(type);
            if (nestedEnums.Length != 0 || nativeDefault || !knownPartial && type.Api.ManagedAttributes.Count != 0)
            {
                Documentation(type); if (!knownPartial) EmitAttributes(type);
                Line($"{Access(type, nested)} partial struct {Id(HandleNetCS.SimpleName(type))}"); Open();
                foreach (var nestedEnum in nestedEnums) Enum(nestedEnum, true);
                if (nativeDefault) EmitNativeDefault(type);
                Close();
            }
            return;
        }
        if (type.MarshalAsError is { } marshalError) { Error(type, marshalError); return; }
        if (HandleNETcpp.IsRoot(type)) { Note(type, "ScriptingObject uses the existing FlaxEngine.Object bridge; no duplicate managed root is emitted."); return; }
        if (type.Api.Template)
        {
            if (type.TemplateParameters.Count == 0) Error(type, "API_STRUCT/API_CLASS(Template) requires a template parameter declaration.");
            else Note(type, $"Template prototype '{type.QualifiedName}' is retained for concrete API_TYPEDEF specializations; the open native template is not emitted as a managed type.");
            return;
        }
        if (type.TypeSymbol?.Declarations.Count(d => d is TypeDescriptor { IsForwardDeclaration: false }) > 1)
            Error(type, "Multiple type definitions resolve to the same symbol.");
        bool isStruct = type is StructDescriptor;
        bool isInterface = type is InterfaceDescriptor;
        if (type.Api.Abstract && (isStruct || isInterface || type.Api.Static || type.IsFinal || type.Api.Sealed))
            Error(type, "API_CLASS(Abstract) requires a non-static, non-final native class.");
        if (type.Api.Static && type.BaseTypes.Count != 0) Error(type, "API_CLASS(Static) cannot project native base types into a C# static class.");
        string kind = isStruct ? "struct" : isInterface ? "interface" : "class";
        List<string> bases = [];
        ClassDescriptor? classBase = null;
        int classBases = 0;
        bool scripting = HandleNETcpp.IsScriptingObject(type);
        if (scripting) bases.AddRange(HandleNetCS.Bases(type));
        foreach (var baseInfo in type.BaseTypes)
        {
            if (type.MarshalAsType != null) continue; // Surrogate conversion does not project native implementation inheritance.
            var declarationType = (baseInfo.Type as NamedTypeInfo)?.Symbol?.Definition;
            if (declarationType is ClassDescriptor { Api.Sealed: true })
                Error(type, $"Cannot emit managed inheritance for '{type.QualifiedName}': base '{declarationType.QualifiedName}' is marked API_CLASS(Sealed). The native inheritance may be valid, but C# cannot derive from its sealed wrapper.");
            if (scripting && declarationType is InterfaceDescriptor && baseInfo.Access != "public") continue;
            if (scripting && declarationType is not InterfaceDescriptor) continue; // Project scripting ancestry and explicit public interfaces, not implementation class bases.
            if (baseInfo.Type is NamedTypeInfo { Symbol: { } baseSymbol } && !plan.HasType(baseSymbol))
            {
                Error(baseSymbol.Definition ?? baseSymbol.Declarations.FirstOrDefault() ?? type, $"Exported {kind} '{type.QualifiedName}' inherits from '{baseSymbol.QualifiedName}', which is not marked [[Export]]. Mark {baseSymbol.QualifiedName} with [[Export]] to include it in C# inheritance.");
                continue;
            }
            if (declarationType is ClassDescriptor) classBases++;
            if (declarationType is not InterfaceDescriptor && (isStruct || isInterface || declarationType is not ClassDescriptor))
            { Error(type, "This base requires composition or an explicit interface projection."); continue; }
            var name = declarationType is InterfaceDescriptor ? HandleNetCS.ManagedName(declarationType) : Map(baseInfo.Type, type, false);
            if (name != null) { bases.Add(name); if (declarationType is ClassDescriptor nativeBase) classBase = nativeBase; }
        }
        if (classBases > 1) Error(type, "Multiple native class bases cannot be C# class inheritance.");
        Documentation(type);
        EmitAttributes(type);
        EmitDeprecated(type.HeaderTokens);
        var nativeStorage = type is StructDescriptor structure && type.MarshalAsType == null ? layout.Struct(structure) : null;
        if (nativeStorage != null) EmitLayout(nativeStorage.Storage);
        else if (isStruct && !type.NativeFieldView) Note(type, "Struct storage layout is not established; no explicit offsets are guessed.");
        string typeHeader = $"{Access(type, nested)} {(type.Api.Static ? "static " : type.Api.Abstract ? "abstract " : (type.IsFinal || type.Api.Sealed) && !isStruct && !isInterface ? "sealed " : "")}partial {kind} {Id(HandleNetCS.SimpleName(type))}" + (bases.Count > 0 ? " : " + string.Join(", ", bases) : "");
        int typeHeaderStart = output.Length;
        Line(typeHeader);
        int typeHeaderLength = output.Length - typeHeaderStart;
        Open();
        Injected(type);
        result.Bindings.Add(new(EmittedBindingKind.Type, type, Id(HandleNetCS.SimpleName(type)), ManagedSourceStart: output.Length, StorageLayout: nativeStorage, ClassBase: classBase,
            ManagedTypeHeader: typeHeader, ManagedTypeHeaderStart: typeHeaderStart, ManagedTypeHeaderLength: typeHeaderLength,
            NativeAccessView: type.MarshalAsType == null && type is StructDescriptor { RequiresNativeFieldAccess: true } or StructDescriptor { NativeFieldView: true }));
        storageScopes.Push(nativeStorage);
        Members(plan.Members(type), isStruct, isInterface, false);
        if (CanEmitNativeDefault(type)) EmitNativeDefault(type);
        storageScopes.Pop();
        Close();
    }

    bool CanEmitNativeDefault(TypeDescriptor type) => type.SourceFile?.Converters.CanonicalValueRecords == true &&
        type is StructDescriptor && !type.Api.NoDefault && !type.Api.InBuild && type.MarshalAsType == null &&
        type.SourceFile.Converters.ManagedValuePartial(type.QualifiedName) == null && type.AutomaticValueConverter != null &&
        !type.Declarations.Any(d => HandleNetCS.SimpleName(d) is "Default" or "__VETCreateDefault");

    void EmitNativeDefault(TypeDescriptor type)
    {
        var resultType = new NamedTypeInfo { Name = type.NativeQualifiedName, Symbol = type.TypeSymbol,
            Resolution = TypeResolution.Resolved, Converter = type.AutomaticValueConverter };
        var factory = new FunctionDescriptor { Parent = type, Name = type.Name with { text = "__VETCreateDefault" },
            NamespaceTokens = type.NamespaceTokens, EnclosingTypeTokens = type.EnclosingTypeTokens.Concat([type.Name]).ToList(),
            GeneratedStatic = true, NativeDefaultFactory = true, TypeInfo = new() { ReturnType = resultType } };
        Line("/// <summary>Returns a fresh value initialized by the native C++ defaults.</summary>");
        Line($"public static {Id(HandleNetCS.SimpleName(type))} Default => __VETCreateDefault();");
        Function(factory, false, true, false, new(StringComparer.Ordinal), "private");
    }

    void Injected(ScopeDescriptor scope)
    {
        foreach (string code in scope.Declarations.SelectMany(d => d.Api.InjectedCode).Where(c => c.Language == "csharp").Select(c => c.Code))
            foreach (string line in code.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n')) Line(line);
    }

    void Members(IEnumerable<DeclarationDescriptor> declarations, bool isStruct, bool isInterface, bool globals)
    {
        var members = declarations.Where(plan.Emits).ToList();
        var fieldNames = new HashSet<string>(members.OfType<FieldDescriptor>().Select(f => f.Name.text), StringComparer.Ordinal);
        var signatures = new Dictionary<string, EmittedSignature>(StringComparer.Ordinal);
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var declaration in members)
        {
            if (declaration is AliasDescriptor alias) { Alias(alias); continue; }
            if (declaration is TypeDescriptor or EnumDescriptor)
            {
                if (IsForward(declaration)) { Forward(declaration, true); continue; }
                if (!names.Add(declaration.Name.text)) Error(declaration, "Duplicate member type or field name.");
                Declaration(declaration, true);
            }
            else if (declaration is FieldDescriptor field)
            {
                if (field.Api.Event)
                {
                    if (EventInterop.Describe(field, out var description, out var reason))
                    {
                        Note(field, description!.Synchronous ? "Event handlers run synchronously on the subscription thread. Wrong-thread invocations are rejected and reported; payload changes are copied back before native execution continues." : "Event handlers use asynchronous owner-thread delivery. Pump pending events on the subscription thread when no suitable SynchronizationContext is available; synchronous side effects/ref/out are not supported by this bridge.");
                        if (description.Synchronous) {
                            Line("/// <summary>Synchronous event handler; native ref arguments are copied back before the callback returns.</summary>");
                            Line(Access(field, true) + " delegate void " + description.SynchronousDelegate + "(" + string.Join(", ", description.Arguments.Select((a, i) => (a.MutableReference ? "ref " : "") + a.Managed + " arg" + i)) + ");");
                        }
                        Documentation(field); EmitAttributes(field);
                        int eventStart = output.Length;
                        string eventDeclaration = $"{Access(field, true)} {(InstanceEventInterop.IsInstance(field) ? "" : "static ")}event {description!.ActionType} {Id(field.Name.text)}";
                        Line(eventDeclaration + " { add => throw new global::System.NotSupportedException(\"Event declaration preview.\"); remove => throw new global::System.NotSupportedException(\"Event declaration preview.\"); }");
                        result.Bindings.Add(new(EmittedBindingKind.Event, field, eventDeclaration, ManagedSourceStart: eventStart, ManagedSourceLength: output.Length - eventStart));
                    }
                    else Error(field, "Cannot bind event '" + field.QualifiedName + "': " + reason);
                    continue;
                }
                if (plan.Properties.TryGetValue(field, out var property))
                {
                    Property(property, isInterface, isStruct, globals);
                    if (!isInterface)
                    {
                        foreach (var accessor in new[] { property.Getter, property.Setter, property.PassThrough }.OfType<FunctionDescriptor>())
                            Function(accessor, false, isStruct, globals, signatures, "private");
                    }
                    continue;
                }
                if (isInterface) { Error(field, "Native interface data fields are not supported."); continue; }
                if (!names.Add(field.Name.text)) Error(field, "Duplicate field or nested type name.");
                if (isStruct && field.Access == "protected") Error(field, "Protected members cannot be represented on a C# struct.");
                string? mapped = field.TypeInfo is ArrayTypeInfo array ? EmitArray(array, field, "__NativeArray_" + field.Name.text, names) : Map(field.TypeInfo, field, false);
                if (mapped == null || mapped == "void") { if (mapped == "void") Error(field, "A field cannot have void type."); continue; }
                if (!Identifier(field.Name.text)) { Error(field, "Invalid field name."); continue; }
                var qualifiers = field.TypeInfo is NamedTypeInfo n ? n.EffectiveQualifiers : field.TypeInfo is PointerTypeInfo p ? p.Qualifiers : TypeQualifiers.None;
                bool isStatic = globals || field.TypeInfo!.SpecifierTokens.Any(t => t.text is "static" or "constexpr" or "consteval");
                bool isReadOnly = (qualifiers & TypeQualifiers.Const) != 0 || field.TypeInfo!.SpecifierTokens.Any(t => t == "constexpr");
                Line("// C++: " + Comment(field.TypeInfo!.OriginalText));
                Documentation(field);
                EmitAttributes(field);
                EmitDeprecated(field.HeaderTokens);
                if (!isStatic && storageScopes.TryPeek(out var containing) && containing != null && containing.Offsets.TryGetValue(field, out int offset))
                {
                    Line($"[global::System.Runtime.InteropServices.FieldOffset({offset})]");
                    EmitScalarMarshal(mapped);
                }
                Line($"{field.Api.ManagedAccess ?? (globals ? "public" : Access(field, true))} {(isStatic ? "static " : "")}{(isReadOnly ? "readonly " : "")}{mapped} {Id(field.Name.text)};");
                result.Bindings.Add(new(EmittedBindingKind.Field, field, mapped + " " + Id(field.Name.text), field.TypeInfo));
                if (!isStatic && !isReadOnly && isStruct && field.Parent is StructDescriptor fieldOwner && field.TypeInfo is not ArrayTypeInfo &&
                    field.Api.ManagedAccess == "private" && storageScopes.TryPeek(out var fieldStorage) && fieldStorage != null)
                {
                    string read = AutomaticFieldConverters.FieldMethod(field, false), write = AutomaticFieldConverters.FieldMethod(field, true);
                    if (!names.Add(read) || !names.Add(write) || fieldOwner.Declarations.Any(d => d.Name.text == read || d.Name.text == write))
                        Error(field, "Generated field conversion helper collides with a declared member.");
                    string ownerName = HandleNetCS.ManagedName(fieldOwner), member = Id(field.Name.text);
                    Line($"internal static {mapped} {read}(in {ownerName} value) => value.{member};");
                    Line($"internal static void {write}(ref {ownerName} value, {mapped} input) => value.{member} = input;");
                }
            }
            else if (declaration is FunctionDescriptor function)
            {
                if (isStruct && function.Access == "protected") Error(function, "Protected members cannot be represented on a C# struct.");
                if (fieldNames.Contains(plan.ManagedName(function))) Error(function, "Generated method conflicts with a field name.");
                if (function.Api.NoProxy && isInterface)
                { Error(function, "API_FUNCTION(NoProxy) cannot be emitted on an interface: a private native-call implementation requires a concrete class or struct."); continue; }
                Function(function, isInterface, isStruct, globals, signatures, function.Api.NoProxy ? "private" : null);
            }
            else Error(declaration, "Raw member needs an explicit generation handler.");
        }
    }

    void Property(PropertyProjection property, bool isInterface, bool isStruct, bool globals)
    {
        var field = property.Field;
        string? mapped = Map(field.TypeInfo, field, false);
        if (mapped == null || mapped == "void") return;
        if (isStruct && property.Access == "protected") { Error(field, "Protected property cannot be represented on a C# struct."); return; }
        string access = field.Api.ManagedAccess ?? (globals ? "public" : property.Access);
        if (property.PassThrough is { } combined)
        {
            if (isInterface) { Error(field, "PassThrough cache requires instance/static storage and is not supported on an interface."); return; }
            if (storageScopes.TryPeek(out var containing) && containing != null && !property.IsStatic && containing.Offsets.TryGetValue(field, out int offset))
            {
                Line($"[global::System.Runtime.InteropServices.FieldOffset({offset})]");
                EmitScalarMarshal(mapped);
            }
            string cache = Id(combined.Name.text + "_" + field.Name.text);
            string method = Id(plan.ManagedName(combined));
            Line($"private {(property.IsStatic || globals ? "static " : "")}{mapped} {cache};");
            Documentation(field);
            EmitAttributes(field);
            EmitDeprecated(field.HeaderTokens);
            Line($"{access} {(property.IsStatic || globals ? "static " : "")}{mapped} {Id(field.Name.text)}"); Open();
            Line($"get => {method}(in {cache});");
            Line($"set => {cache} = {method}(in value);");
            Close();
            result.Bindings.Add(new(EmittedBindingKind.Property, field, mapped + " " + Id(field.Name.text), field.TypeInfo, Property: property));
            return;
        }
        Documentation(field);
        EmitAttributes(field);
        EmitDeprecated(field.HeaderTokens);
        Line($"{access} {(property.IsStatic || globals ? "static " : "")}{mapped} {Id(field.Name.text)}"); Open();
        Accessor(property.Getter, "get");
        Accessor(property.Setter, "set");
        Close();
        result.Bindings.Add(new(EmittedBindingKind.Property, field, mapped + " " + Id(field.Name.text), field.TypeInfo, Property: property));
        void Accessor(FunctionDescriptor? endpoint, string keyword)
        {
            if (endpoint == null) return;
            bool differentAccess = field.Api.ManagedAccess == null && property.Getter != null && property.Setter != null && endpoint.Access != access;
            string visibility = differentAccess ? endpoint.Access + " " : "";
            Line("// Native accessor: " + endpoint.QualifiedName);
            string argument = keyword == "get" ? "" : endpoint.Fields[0].Binding?.Passing == ParameterPassing.LValueReference ? endpoint.Fields[0].Binding?.Direction == ParameterDirection.Ref ? "ref value" : "in value" : "value";
            Line(isInterface ? visibility + keyword + ";" : visibility + keyword + " => " + Id(plan.ManagedName(endpoint)) + "(" + argument + ");");
        }
    }

    void Function(FunctionDescriptor function, bool isInterface, bool isStruct, bool globals, Dictionary<string, EmittedSignature> signatures, string? accessOverride = null)
    {
        if (function.Binding?.RedeclarationOf != null) return;
        if (function.TypeInfo is not { } signature) { Error(function, "Missing function type information."); return; }
        var deleted = signature.SuffixTokens.SkipWhile(t => t != "=").Skip(1).FirstOrDefault(t => !t.IsTrivia);
        if (deleted == "delete")
        {
            Line("// Deleted native declaration omitted: " + Comment(function.Name.text));
            return;
        }
        if (signature.IsDestructor)
        {
            string destroyName = "__NativeDestroy_" + (function.Parent?.Name.text ?? "Object");
            if (!signatures.TryAdd(destroyName + "()", new(function, "void " + Id(destroyName) + "()", Array.Empty<string>()))) Error(function, "Destructor preview name collision.");
            Note(function, "Destructor emitted as a named throwing stub, not a managed finalizer or ownership transfer.");
            Documentation(function);
            Line($"{Access(function, true)} void {Id(destroyName)}() => throw new global::System.NotSupportedException(\"Native destructor preview; no lifetime backend.\");");
            result.Bindings.Add(new(EmittedBindingKind.Destructor, function, "void " + Id(destroyName) + "()", NativeFunction: signature));
            return;
        }
        if (signature.ReferenceQualifier != null) { Error(function, "Ref-qualified native method needs an explicit receiver mapping."); return; }
        if (signature.IsConstructor && function.Parent is ClassDescriptor { Api.Abstract: true })
        { Error(function, $"Cannot expose constructor '{function.QualifiedName}': API_CLASS(Abstract) forbids direct native construction. Export a concrete derived class constructor or a factory instead."); return; }
        if (!Identifier(function.Name.text)) { Error(function, "Operator or invalid method name needs a handler."); return; }
        // A value property cannot safely expose a borrowed ref into a native class.
        // Copy through its established aggregate converter; ordinary ref-returning
        // methods and inline struct aliases retain their separate lifetime rules.
        bool copyPropertyReturn = function.Parent is ClassDescriptor && plan.Properties.Values.Any(p => p.Getter == function) &&
            signature.ReturnType is ReferenceTypeInfo { ReferenceKind: ReferenceKind.LValue, Referent: NamedTypeInfo { EffectiveQualifiers: TypeQualifiers.Const, Converter: { AutomaticFields: true, Bodies: not null } } };
        string? returns = signature.IsConstructor ? "" : Map(copyPropertyReturn ? ((ReferenceTypeInfo)signature.ReturnType!).Referent : signature.ReturnType, function, false, !copyPropertyReturn);
        if (returns == null) return;
        List<string> parameters = [], mappedTypes = [], keys = [];
        List<string> emittedParameterNames = [];
        var parameterNames = new HashSet<string>(StringComparer.Ordinal);
        var declaredParameterNames = new HashSet<string>(function.Fields.Where(f => !f.IsUnnamed).Select(f => f.Name.text), StringComparer.Ordinal);
        for (int i = 0; i < function.Fields.Count; i++)
        {
            var field = function.Fields[i];
            string name = field.IsUnnamed ? "__arg" + i : field.Name.text;
            if (field.IsUnnamed)
                while (declaredParameterNames.Contains(name) || parameterNames.Contains(name)) name += "_";
            if (!Identifier(name) || !parameterNames.Add(name)) { Error(field, "Invalid or conflicting generated parameter name."); return; }
            string? type = MapParameter(field);
            if (type == null || type == "void") { if (type == "void") Error(field, "Named void parameter is invalid."); return; }
            parameters.Add(AttributePrefix(field) + type + " " + Id(name));
            emittedParameterNames.Add(Id(name));
            mappedTypes.Add(type);
            keys.Add(type.StartsWith("in ") || type.StartsWith("ref ") || type.StartsWith("out ") ? "byref " + (type.StartsWith("ref readonly ") ? type[13..] : type[(type.IndexOf(' ') + 1)..]) : type);
        }
        string?[] defaults = new string?[parameters.Count];
        bool[] strippedDefaults = new bool[parameters.Count];
        for (int i = parameters.Count - 1; i >= 0; --i)
        {
            var parameter = function.Fields[i];
            string value = string.Concat((parameter.Api.DefaultValueTokens ?? parameter.InitializerTokens).Where(t => !t.IsTrivia).Select(t => t.text));
            string expanded = parameter.ExpandedInitializerTokens is { } tokens ? DefaultMacroExpansion.Normalize(tokens) : value;
            string literalType = mappedTypes[i].StartsWith("in ", StringComparison.Ordinal) ? mappedTypes[i][3..] : mappedTypes[i];
            string? literal = OptionalLiteral(literalType, expanded);
            var defaultType = parameter.Binding?.EffectiveType ?? parameter.TypeInfo;
            if (defaultType is ReferenceTypeInfo defaultReference) defaultType = defaultReference.Referent;
            if (literal == null) literal = EnumOptionalLiteral(defaultType, literalType, expanded, parameter);
            if (literal == null && defaultType is NamedTypeInfo { Converter.Bodies: { } defaultConverter } &&
                (mappedTypes[i] == defaultConverter.ManagedType || mappedTypes[i] == "in " + defaultConverter.ManagedType))
                literal = defaultConverter.ManagedOptionalDefault?.Invoke(expanded);
            if (HandleNETcpp.Use(parameter.TypeInfo) is { Pointer: true, Slot: false } && value is "nullptr" or "NULL" or "0" or "null") literal = "null";
            if (defaultType is PointerTypeInfo && mappedTypes[i] is "nint" or "nuint" && value == "null") literal = "0";
            defaults[i] = literal;
            if (literal != null) parameters[i] += " = " + literal;
            else if (value.Length != 0)
            {
                strippedDefaults[i] = true;
                Note(parameter, $"Unsupported C# default argument '{value}' for parameter '{parameter.Name.text}' in function '{function.NativeQualifiedName}'.\n" +
                    "C# optional parameter defaults must be compile-time constants; static fields and properties cannot be used.\n" +
                    "The default value was omitted from the generated binding; the parameter remains required and is placed before optional parameters.");
            }
        }
        // Only the public declaration changes order. The manifest parameters below
        // remain in native order, so marshalling and DLL argument positions do not change.
        var managedOrder = Enumerable.Range(0, parameters.Count)
            .OrderBy(i => strippedDefaults[i] ? 0 : defaults[i] == null ? 1 : 2).ToArray();
        var managedParameters = managedOrder.Select(i => parameters[i]).ToArray();
        string managedName = plan.ManagedName(function);
        string key = managedName + "(" + string.Join(",", managedOrder.Select(i => keys[i])) + ")";
        var current = new EmittedSignature(function, (returns.Length == 0 ? "" : returns + " ") + Id(managedName) + "(" + string.Join(", ", managedParameters) + ")", managedOrder.Select(i => mappedTypes[i]).ToArray());
        if (signatures.TryGetValue(key, out var previous))
        {
            Error(function, Collision(previous, current));
            return;
        }
        signatures.Add(key, current);
        bool isStatic = globals || BindingSignaturePass.IsStatic(function);
        Documentation(function);
        if (accessOverride == null) EmitAttributes(function);
        EmitDeprecated(function.HeaderTokens);
        string access = accessOverride ?? function.Api.ManagedAccess ?? (globals ? "public" : Access(function, true));
        string dispatch = "";
        if (accessOverride == null && !isInterface && !isStruct && !isStatic && !signature.IsConstructor)
        {
            if (function.Api.Sealed)
            {
                if (HasExportedOverrideTarget(function)) dispatch = "new ";
            }
            else if (signature.SuffixTokens.Any(t => t == "override") && HasExportedOverrideTarget(function)) dispatch = "override ";
            else if (signature.ReturnType?.SpecifierTokens.Any(t => t == "virtual") == true && function.Parent is not TypeDescriptor { IsFinal: true } && function.Parent is not TypeDescriptor { Api.Sealed: true }) dispatch = "virtual ";
        }
        string head = signature.IsConstructor ? $"{access} {Id(HandleNetCS.SimpleName(function.Parent!))}" :
            $"{access} {(isStatic ? "static " : dispatch)}{returns} {Id(managedName)}";
        string args = "(" + string.Join(", ", managedParameters) + ")";
        int sourceStart = output.Length;
        Line(isInterface ? head + args + ";" : head + args + " => throw new global::System.NotSupportedException(\"Declaration preview; native call generation is not implemented.\");");
        var emittedParameters = function.Fields.Select((parameter, i) => new EmittedParameter(parameters[i],
            parameter.Binding!.EffectiveType, parameter.Binding.Direction, parameter.Binding.Passing, mappedTypes[i], emittedParameterNames[i], PointerArrayInterop.Describe(parameter))).ToArray();
        result.Bindings.Add(new(EmittedBindingKind.Function, function, head + args, signature.ReturnType, emittedParameters, accessOverride != null, NativeFunction: signature,
            ManagedSourceStart: sourceStart, ManagedSourceLength: output.Length - sourceStart, ManagedReturnType: returns, CopyReferenceReturn: copyPropertyReturn));
    }

    bool HasExportedOverrideTarget(FunctionDescriptor function)
    {
        if (function.Parent is not TypeDescriptor owner) return false;
        HashSet<TypeDescriptor> visited = [];
        return Search(owner);
        bool Search(TypeDescriptor type)
        {
            if (!visited.Add(type)) return false;
            foreach (var baseInfo in type.BaseTypes)
            {
                if (baseInfo.Type is not NamedTypeInfo { Symbol: { Definition: ClassDescriptor parent } symbol } || !plan.HasType(symbol)) continue;
                foreach (var candidate in parent.Functions.Where(plan.Emits))
                {
                    if (candidate.Name.text != function.Name.text || candidate.Access == "private" ||
                        candidate.Fields.Count != function.Fields.Count || candidate.TypeInfo == null) continue;
                    bool virtualMethod = candidate.TypeInfo.ReturnType?.SpecifierTokens.Any(t => t == "virtual") == true ||
                        candidate.TypeInfo.SuffixTokens.Any(t => t == "override");
                    if (virtualMethod && candidate.Fields.Zip(function.Fields).All(pair =>
                        pair.First.TypeInfo != null && pair.Second.TypeInfo != null &&
                        BindingSignaturePass.Canonical(pair.First.TypeInfo, true) == BindingSignaturePass.Canonical(pair.Second.TypeInfo, true))) return true;
                }
                if (Search(parent)) return true;
            }
            return false;
        }
    }

    static string? EnumOptionalLiteral(Text.TypeInfo? type, string managedType, string expression, FieldDescriptor parameter)
    {
        if (type is not NamedTypeInfo { Converter: { EnumValue: true, Bodies: { } bodies }, Symbol.Definition: EnumDescriptor enumeration } ||
            managedType != bodies.ManagedType || parameter.SourceFile?.TypeInfos is not { } analysis ||
            !Regex.IsMatch(expression, @"^(::)?[A-Za-z_]\w*(::[A-Za-z_]\w*)+$")) return null;
        int separator = expression.LastIndexOf("::", StringComparison.Ordinal);
        string member = expression[(separator + 2)..];
        if (!enumeration.Members.Any(m => m.Name.text == member)) return null;
        // Resolve the qualifier in the declaration's lexical scope. Merely
        // replacing :: with . would accept unrelated enum/static-field defaults.
        var qualifier = Tokenizer.Tokenize(expression[..separator]).Where(t => !t.IsTrivia && t.kind != Token.Kind.EndOfFile).ToList();
        var resolved = TypeInfoPass.Parse(qualifier, parameter, analysis);
        if (resolved is not NamedTypeInfo { Symbol.Definition: EnumDescriptor actual } || actual != enumeration) return null;
        return bodies.ManagedType + "." + Id(member);
    }

    static string? OptionalLiteral(string type, string value)
    {
        if (type == "bool" && value is "true" or "false") return value;
        if (type is "nint" or "nuint" && value == "nullptr") return "0";
        if (type is "float" or "double")
        {
            // Decimal literals only: no macros, expressions, hex floats or long double.
            // Preserve source precision: a native 0.1f promoted to double is not 0.1d.
            bool floating = Regex.IsMatch(value, @"^[+-]?(?:(?:[0-9]+\.[0-9]*|\.[0-9]+)(?:[eE][+-]?[0-9]+)?|[0-9]+[eE][+-]?[0-9]+)[fF]?$");
            if (!floating && !Regex.IsMatch(value, @"^[+-]?(?:0|[1-9][0-9]*)$")) return null;
            // Avoid double rounding when a large integer is converted directly to native float.
            if (!floating && type == "float" && System.Numerics.BigInteger.TryParse(value, out var integerDefault) &&
                System.Numerics.BigInteger.Abs(integerDefault) > 9007199254740992L) return null;
            bool singleSource = value.EndsWith('f') || value.EndsWith('F');
            string text = singleSource ? value[..^1] : value;
            var culture = System.Globalization.CultureInfo.InvariantCulture;
            const System.Globalization.NumberStyles style = System.Globalization.NumberStyles.Float;
            double floatingValue;
            if (singleSource)
            {
                if (!float.TryParse(text, style, culture, out var single) || !float.IsFinite(single)) return null;
                floatingValue = single;
            }
            else if (!double.TryParse(text, style, culture, out floatingValue) || !double.IsFinite(floatingValue)) return null;
            if (type == "double") return floatingValue.ToString("R", culture) + "D";
            float converted = (float)floatingValue;
            return float.IsFinite(converted) ? converted.ToString("R", culture) + "F" : null;
        }
        // C++ leading-zero literals are octal, and unary minus on unsigned literals
        // wraps before conversion to the parameter type. Neither is decimal parsing.
        var integer = Regex.Match(value, @"^(?<sign>[+-]?)(?<digits>0|[1-9][0-9]*)(?<suffix>[uU](?:[lL]|ll|LL)?|(?:[lL]|ll|LL)[uU]?)?$");
        if (!integer.Success) return null;
        bool unsignedSource = integer.Groups["suffix"].Value.Contains('u', StringComparison.OrdinalIgnoreCase);
        if (unsignedSource && integer.Groups["sign"].Value == "-") return null;
        if (!System.Numerics.BigInteger.TryParse(integer.Groups["digits"].Value, System.Globalization.NumberStyles.None,
            System.Globalization.CultureInfo.InvariantCulture, out var number)) return null;
        if (number > (unsignedSource ? new System.Numerics.BigInteger(ulong.MaxValue) : new System.Numerics.BigInteger(long.MaxValue))) return null;
        if (integer.Groups["sign"].Value == "-") number = -number;
        (long Min, ulong Max, string Suffix)? bounds = type switch
        {
            "sbyte" => (sbyte.MinValue, (ulong)sbyte.MaxValue, ""), "byte" => (0, byte.MaxValue, ""),
            "short" => (short.MinValue, (ulong)short.MaxValue, ""), "ushort" => (0, ushort.MaxValue, ""),
            "int" => (int.MinValue, int.MaxValue, ""), "uint" => (0, uint.MaxValue, "U"),
            "long" => (long.MinValue, long.MaxValue, "L"), "ulong" => (0, ulong.MaxValue, "UL"), _ => null
        };
        return bounds is { } range && number >= range.Min && number <= range.Max ? number.ToString(System.Globalization.CultureInfo.InvariantCulture) + range.Suffix : null;
    }

    static string Collision(EmittedSignature previous, EmittedSignature current)
    {
        StringBuilder message = new();
        message.Append("Defined ").Append(NativeText(previous.Native.HeaderTokens).TrimEnd(';'))
            .Append(" has collided with ").Append(NativeText(current.Native.HeaderTokens).TrimEnd(';')).AppendLine(".");
        int parametersAt = current.Managed.IndexOf('(');
        string method = parametersAt >= 0 ? current.Managed[..parametersAt] : current.Managed;
        message.Append("Unable to resolve \"").Append(Readable(method)).Append("(...)\": ");
        List<string> modifiers = [];
        for (int i = 0; i < previous.ParameterTypes.Count && i < current.ParameterTypes.Count; i++)
        {
            string before = Mode(previous.ParameterTypes[i]);
            string after = Mode(current.ParameterTypes[i]);
            if (before != after) modifiers.Add($"'{before}' versus '{after}'");
        }
        if (modifiers.Count > 0)
            message.Append("C# forbids distinguishing overloads solely by ").Append(string.Join("; ", modifiers.Distinct())).Append('.');
        else if (previous.Native.TypeInfo?.Qualifiers != current.Native.TypeInfo?.Qualifiers)
            message.Append("native method const/volatile qualifiers do not distinguish C# overloads.");
        else message.Append("different native parameter types map to the same C# parameter types.");
        message.AppendLine();
        message.AppendLine("In:");
        Location(previous.Native);
        Location(current.Native);
        return message.ToString().TrimEnd();

        static string Mode(string type) => type.StartsWith("ref ") ? "ref" : type.StartsWith("in ") ? "in" : type.StartsWith("out ") ? "out" : "value";
        static string Readable(string signature) => Regex.Replace(signature, @"global::(?:@?[A-Za-z_][A-Za-z0-9_]*\.)+(@?[A-Za-z_][A-Za-z0-9_]*)", "$1");

        void Location(FunctionDescriptor native)
        {
            DeclarationDescriptor? owner = native;
            while (owner != null && owner is not FileDescriptor) owner = owner.Parent;
            message.Append("  ").Append((owner as FileDescriptor)?.Path ?? "<source>")
                .Append('(').Append(native.Name.line + 1).Append(',').Append(native.Name.col + 1).AppendLine(")");
        }
    }

    static string NativeText(IEnumerable<Token> tokens, bool declaration = true)
    {
        StringBuilder text = new();
        bool space = false;
        foreach (var token in tokens)
        {
            if (token.IsTrivia) { space = text.Length > 0; continue; }
            if (space) text.Append(' ');
            text.Append(token.text);
            space = false;
        }
        if (declaration && text.Length > 0 && text[^1] != ';') text.Append(';');
        return text.ToString();
    }

    string? Map(Text.TypeInfo? type, DeclarationDescriptor context, bool parameter, bool returns = false)
    {
        if (type == null) { Error(context, "Missing type information."); return null; }
        if (HandleNETcpp.Contains(type))
        {
            if (HandleNETcpp.SupportedUse(type) && !(returns && HandleNETcpp.Use(type)!.Slot)) return HandleNetCS.ObjectType(type);
            Error(context, $"Flax scripting object type '{type.Display}' requires a supported object pointer/reference shape; value copies, deep pointers and pointer-slot returns are not emitted."); return null;
        }
        if (context.SourceFile?.Converters.FlaxScriptingObjects == true)
        {
            if (RuntimeHandleInterop.Kind(type) is { } runtimeKind) return RuntimeHandleInterop.Managed(runtimeKind);
            if (RuntimeHandleInterop.Contains(type))
            { Error(context, $"Runtime handle '{type.Display}' requires an explicit ownership adapter for this shape. Only single non-volatile MArray*/MType* parameters and value returns use the host marshallers; pointer slots, deep pointers and references are not inferred."); return null; }
        }
        if (type is UnsupportedTypeInfo unsupported) { Error(context, $"Cannot bind '{context.QualifiedName}' ({unsupported.OriginalText}): {unsupported.Reason}"); return null; }
        if (type is FunctionPointerTypeInfo callback)
        {
            if (!callback.IsSupported) { Error(context, "Function pointer signature has unsupported declarators."); return null; }
            Note(context, "Function pointer is an opaque nint; no calling convention, delegate or ownership is inferred.");
            return "nint";
        }
        if (type is PointerTypeInfo pointer)
        {
            if (pointer.Pointee is UnsupportedTypeInfo) { Error(context, "Unsupported pointer declarator."); return null; }
            // An address is only an address: never Nullable<T> or an owning object.
            return "nint";
        }
        if (type is ReferenceTypeInfo reference)
        {
            if (returns && reference.Referent is NamedTypeInfo { Converter.Bodies.CopyReferenceReturns: true })
                return Map(reference.Referent, context, false, true);
            if (returns && reference.Referent is NamedTypeInfo { Converter: { IsAlias: false, SharedReference: false } })
            { Error(context, $"A reference return in '{context.QualifiedName}' requires a shared native layout/lifetime converter; a scalar value converter cannot expose it as ref."); return null; }
            if (!parameter && !returns) { Error(context, "Reference fields need an explicit lifetime/storage policy."); return null; }
            if (reference.ReferenceKind == ReferenceKind.RValue) { Error(context, "Rvalue references need an explicit move/ownership policy."); return null; }
            string? inner = Map(reference.Referent, context, false);
            if (inner == null || inner == "void") return null;
            bool readOnly = reference.Referent is NamedTypeInfo n && (n.EffectiveQualifiers & TypeQualifiers.Const) != 0 ||
                reference.Referent is PointerTypeInfo p && (p.Qualifiers & TypeQualifiers.Const) != 0;
            return (returns ? readOnly ? "ref readonly " : "ref " : readOnly ? "in " : "ref ") + inner;
        }
        if (type is ArrayTypeInfo) { Error(context, "Native arrays need an explicit extent/layout mapping; they are not managed arrays by default."); return null; }
        if (type is not NamedTypeInfo named) { Error(context, "Missing named type handler."); return null; }
        if (named.Converter is { } converter)
        {
            if (converter.Bodies?.BorrowedObjectElements == true)
            {
                var endpoint = context as FunctionDescriptor;
                if (context is FieldDescriptor projected && plan.Properties.TryGetValue(projected, out var property) && property.Setter == null) endpoint = property.Getter;
                bool borrowedView = converter.Bodies.BorrowedObjectViewReturn && endpoint?.TypeInfo?.ReturnType is NamedTypeInfo;
                if (parameter || (!returns && context is not FieldDescriptor) || (!borrowedView && endpoint?.TypeInfo?.ReturnType is not ReferenceTypeInfo { ReferenceKind: ReferenceKind.LValue, Referent: NamedTypeInfo { EffectiveQualifiers: TypeQualifiers.Const } }))
                { Error(context, "No converter for this inline engine-object array use: a native-owned const-reference return is required. Inputs, value returns, Out/Ref construction and nested snapshots cannot copy or retain those native objects."); return null; }
            }
            var adapterType = named.Specialization?.Concrete ?? named.Symbol?.Definition as TypeDescriptor;
            if (converter.RepresentationAdapter && adapterType is { Api.InBuild: false, TypeSymbol: { } adapterSymbol } && !plan.HasType(adapterSymbol))
            { Error(context, $"Type used by an exported declaration has a MarshalAs converter but its managed counterpart is not exported: {adapterType.QualifiedName}. Export its containing types or mark an existing managed implementation InBuild."); return null; }
            var abi = Map(converter.AbiType(), context, parameter, returns);
            if (converter.Bodies is not { } bodies) return abi;
            try { ScalarAbi.Require(converter); }
            catch (ArgumentException error) { Error(context, error.Message); return null; }
            return bodies.ManagedType;
        }
        var definition = named.Specialization?.Concrete ?? named.Symbol?.Definition as TypeDescriptor;
        if (definition?.MarshalAsError is { } marshalFailure) { Error(context, "No converter: " + marshalFailure); return null; }
        if (definition?.Api.InBuild == true)
        { Error(context, $"No converter registered for InBuild type '{named.Display}'. InBuild suppresses generation; it does not supply an ABI mapping for the existing managed implementation."); return null; }
        if (named.Arguments.Count > 0)
        {
            if (named.Specialization?.Concrete is { } concrete)
            {
                return "global::" + Qualified(concrete.QualifiedName);
            }
            if (named.Resolution == TypeResolution.Resolved && named.Symbol?.Definition is TypeDescriptor { Api.Template: true })
                Error(context, $"Resolved exported template '{named.Display}'{(named.NativeAliasSpelling != null ? " through native typedef '" + named.NativeAliasSpelling + "'" : "")}. Concrete specialization emission is required before this type can be used in C#; no layout or template substitution is guessed.");
            else Error(context, MissingConverter(named, context) + " No specialization converter is registered.");
            return null;
        }
        if (named.Symbol?.Definition is TypeDescriptor { Api.Template: true })
        { Error(context, $"Resolved exported template '{named.Display}' requires concrete type arguments. Default arguments, parameter packs and open template uses need an explicit instantiation handler; an open template is not emitted as a concrete C# type."); return null; }
        if (named.Resolution == TypeResolution.Builtin)
        {
            var words = named.Name.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            bool unsigned = words.Contains("unsigned");
            int longs = words.Count(w => w == "long");
            if (words.Contains("void")) return "void";
            if (words.Contains("bool")) return "bool";
            if (words.Contains("float")) return "float";
            if (words.Contains("double"))
            { if (longs != 0) { Error(context, "long double mapping is not registered."); return null; } return "double"; }
            if (words.Contains("char16_t") || words.Contains("wchar_t")) return "char";
            if (words.Contains("char32_t")) return "uint";
            if (words.Contains("char8_t")) return "byte";
            if (words.Contains("char")) return unsigned ? "byte" : "sbyte";
            if (words.Contains("short")) return unsigned ? "ushort" : "short";
            if (longs >= 2) return unsigned ? "ulong" : "long";
            // windows-x64 uses LLP64; C++ long is 32-bit, not C# long.
            return unsigned ? "uint" : "int";
        }
        if (named.Resolution != TypeResolution.Resolved || named.Symbol?.Definition == null)
        { Error(context, MissingConverter(named, context)); return null; }
        if (named.Symbol.Definition.SourceFile is { } owner && owner.Errors.Any(entry => entry.IsError))
        { Error(named.Symbol.Definition, $"Cannot use type '{named.Symbol.QualifiedName}': its declaring header has parser errors. Resolve those errors before emitting a binding that depends on it."); return null; }
        if (!plan.HasType(named.Symbol)) { Error(context, "Type used by an exported declaration is not marked [[Export]]: " + named.Symbol.QualifiedName); return null; }
        return HandleNetCS.ManagedName(named.Symbol.Definition);
    }

    string? MapParameter(FieldDescriptor parameter)
    {
        if (PointerArrayInterop.Configured(parameter))
        {
            if (PointerArrayInterop.Describe(parameter) is { } buffer) return HandleNetCS.ManagedName(buffer.Element) + "[]";
            Error(parameter, "Configured input pointer-array contract requires a public engine-object T** buffer and a named signed 32-bit value count, without Ref/Out overrides."); return null;
        }
        if (HandleNetCS.Parameter(parameter) is { } scripting) return scripting;
        var binding = parameter.Binding;
        if (binding == null) { Error(parameter, "Missing parameter access/direction analysis."); return null; }
        if (binding.Passing == ParameterPassing.RValueReference && binding.EffectiveType is ReferenceTypeInfo { Referent: NamedTypeInfo { Converter.Bodies.MoveInputs: true } moved })
            return Map(moved, parameter, false);
        if (parameter.SourceFile?.Converters.FlaxScriptingObjects == true && binding.Passing == ParameterPassing.LValueReference && RuntimeHandleInterop.Contains(binding.EffectiveType))
        { Error(parameter, $"Runtime handle '{binding.EffectiveType.Display}' requires an explicit ownership adapter for a reference/pointer slot; the host marshaller supports a copied single handle only."); return null; }
        if (binding.Passing == ParameterPassing.LValueReference && binding.EffectiveType is ReferenceTypeInfo reference)
        {
            if (binding.Direction == ParameterDirection.Ref && reference.Referent is NamedTypeInfo { Converter: { IsAlias: false, SharedReference: false } codec } && codec.Bodies?.CopyReferenceParameters != true)
            { Error(parameter, $"Parameter '{parameter.Name.text}' in '{parameter.Parent?.QualifiedName}' requires a shared ref converter or copy-in/copy-back converter for '{reference.Referent.Display}'; the registered value converter only supports In/Out."); return null; }
            var referent = Map(reference.Referent, parameter, false);
            if (referent == null || referent == "void") return null;
            string prefix = binding.ReadOnlyReference ? "ref readonly " : binding.Direction switch { ParameterDirection.Out => "out ", ParameterDirection.Ref => "ref ", _ => "in " };
            return prefix + referent;
        }
        // A copied pointer does not become ref nint just because its target is writable.
        return Map(binding.EffectiveType, parameter, true);
    }

    static string MissingConverter(NamedTypeInfo type, DeclarationDescriptor context)
    {
        string use = context is FieldDescriptor { IsParameter: true } parameter
            ? $"parameter '{parameter.Name.text}' of function '{parameter.Parent?.QualifiedName}'"
            : context is FunctionDescriptor ? $"return type of function '{context.QualifiedName}'" : $"declaration '{context.QualifiedName}'";
        if (type.Resolution == TypeResolution.Ambiguous)
            return $"Ambiguous native type '{type.Display}' in {use}: the source index contains conflicting definitions/aliases. Supply configuration-specific source inputs or an explicit converter; no candidate was selected.";
        return $"No converter or usable declaration info for native type '{type.Display}' in {use}. RegisterAlias/RegisterConverter or provide its typedef declaration. Includes and macros are not expanded (unresolved/incomplete type).";
    }

    void Enum(EnumDescriptor enumeration, bool nested)
    {
        if (enumeration.TypeSymbol?.Declarations.Count(d => d is EnumDescriptor { IsForwardDeclaration: false }) > 1)
            Error(enumeration, "Multiple enum definitions resolve to the same symbol.");
        string? underlying = enumeration.UnderlyingType == null ? "int" : Map(enumeration.UnderlyingType, enumeration, false);
        if (enumeration.UnderlyingType == null && !enumeration.IsScoped)
            Note(enumeration, "Unscoped enum uses int in the declaration preview; native underlying type is still unresolved and must be established before interop.");
        if (underlying is not ("sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong"))
        { Error(enumeration, "Unsupported enum underlying type."); return; }
        string enumName = CSharpNameValidator.EnumName(enumeration);
        if (!Identifier(enumName)) { Error(enumeration, "Invalid enum name."); return; }
        if (string.IsNullOrEmpty(enumeration.Name.text)) Note(enumeration, "Anonymous enum grouped under " + enumName + " for the C# preview.");
        Documentation(enumeration);
        EmitAttributes(enumeration);
        if (enumeration.Api.Flags) Line("[global::System.Flags]");
        EmitDeprecated(enumeration.HeaderTokens);
        Line($"{Access(enumeration, nested)} enum {Id(enumName)} : {underlying}"); Open();
        result.Bindings.Add(new(EmittedBindingKind.Enum, enumeration, Id(enumName), enumeration.UnderlyingType));
        foreach (var member in enumeration.Members) EnumMember(enumeration, member);
        Close();
    }

    void EnumMember(EnumDescriptor owner, EnumMemberDescriptor member)
    {
        result.Diagnostics.AddRange(member.Api.Errors);
        result.Notes.AddRange(member.Api.Warnings);
        var tokens=member.HeaderTokens;
        var comments = tokens.TakeWhile(t => t.IsTrivia).Where(t => t.kind == Token.Kind.Comment).ToList();
        if (!Identifier(member.Name.text)) { Error(member, "Invalid enumerator name."); return; }
        string name = Id(member.Name.text);
        Documentation(comments);
        EmitAttributes(member);
        EmitDeprecated(tokens);
        if (member.ValueTokens.Count==0) { Line(name + ","); return; }
        var expression = (member.ExpandedValueTokens ?? member.ValueTokens).ToList();
        string? cast = null;
        int brace = expression.FindIndex(t => t == "{");
        if (brace > 0 && expression[^1] == "}")
        {
            var scratch = new TypeAnalysisResult();
            var castType = TypeInfoPass.Parse(expression.Take(brace).ToList(), owner, scratch);
            if (castType is not NamedTypeInfo { Resolution: TypeResolution.Builtin }) { Error(owner, "Enum expression cast must be a known integral builtin."); return; }
            cast = Map(castType, owner, false);
            if (cast is not ("sbyte" or "byte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "char"))
            { Error(owner, "Enum expression cast must be integral."); return; }
            expression = expression.Skip(brace + 1).SkipLast(1).ToList();
        }
        if (expression.Count == 0 || expression.Any(t => t.kind is Token.Kind.String or Token.Kind.Character ||
            t.text.Any(c => !(char.IsLetterOrDigit(c) || "_()+-~|&^<> ".Contains(c)))))
        { Error(owner, "Enum expression requires a constant-expression translation handler."); return; }
        string value = string.Concat(expression.Select(t => t.text));
        value = Regex.Replace(value, @"\b(0[xX][0-9a-fA-F]+|[0-9]+)(?:ULL|LLU|ull|llu)\b", "$1UL");
        value = Regex.Replace(value, @"\b(0[xX][0-9a-fA-F]+|[0-9]+)(?:LL|ll)\b", "$1L");
        value = Regex.Replace(value, @"\b[A-Za-z_][A-Za-z0-9_]*\b", m => Id(m.Value));
        if (cast != null) value = "(" + cast + ")(" + value + ")";
        // Identifier tokens and numeric suffix fragments must remain intact.
        // The C# compiler is the final syntax/constant-value check in this preview.
        Line(name + " = " + value + ",");
    }

    static bool IsForward(DeclarationDescriptor declaration) => declaration is TypeDescriptor { IsForwardDeclaration: true } or EnumDescriptor { IsForwardDeclaration: true };
    void Forward(DeclarationDescriptor declaration, bool nested)
    {
        TypeSymbol? symbol = declaration is TypeDescriptor type ? type.TypeSymbol : ((EnumDescriptor)declaration).TypeSymbol;
        if (symbol?.Definition != null) return;
        if (symbol != null && !emittedOpaqueTypes.Add(symbol)) return;
        if (declaration is EnumDescriptor enumeration) { Enum(enumeration, nested); return; }
        if (!Identifier(declaration.Name.text)) { Error(declaration, "Invalid opaque type name."); return; }
        Note(declaration, "Incomplete native type emitted as an opaque address record; by-value use is still rejected.");
        Documentation(declaration);
        Line($"{Access(declaration, nested)} readonly partial struct {Id(declaration.Name.text)}"); Open();
        result.Bindings.Add(new(EmittedBindingKind.OpaqueType, declaration, Id(declaration.Name.text)));
        Documentation(Array.Empty<Token>());
        Line("public readonly nint Address;");
        Close();
    }
    string? EmitArray(ArrayTypeInfo array, FieldDescriptor field, string name, HashSet<string> names, bool rootArray = true)
    {
        string extent = string.Concat(array.EffectiveExtentTokens.Select(t => t.text));
        if (!int.TryParse(extent, out int count) || count <= 0)
        { Error(field, "Array extent must currently be a positive decimal literal."); return null; }
        if (!names.Add(name)) { Error(field, "Generated array helper name collision: " + name); return null; }
        string? element = array.ElementType is ArrayTypeInfo nested ? EmitArray(nested, field, name + "_Element", names, false) : Map(array.ElementType, field, false);
        if (element == null || element == "void") return null;
        var storage = layout.Storage(array);
        var elementStorage = layout.Storage(array.ElementType);
        if (storage == null || elementStorage == null) { Error(field, "Array element storage/layout is not established."); return null; }
        int pack = storage.Alignment;
        if (rootArray && !NativeLayout.Alignment(field.HeaderTokens, pack, out pack))
        { Error(field, "Array alignas expression is not supported by explicit-layout generation."); return null; }
        bool fixedPrimitive = element is "char" or "byte" or "sbyte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double";
        if (!fixedPrimitive && count > 4096) { Error(field, "Non-primitive explicit array exceeds the 4096-field generation limit."); return null; }
        Documentation(Array.Empty<Token>());
        EmitLayout(new NativeStorage(storage.Size, pack));
        Line($"{Access(field, true)} {(fixedPrimitive ? "unsafe " : "")}struct {Id(name)}"); Open();
        if (fixedPrimitive)
        {
            Documentation(Array.Empty<Token>());
            Line("[global::System.Runtime.InteropServices.FieldOffset(0)]");
            Line($"public fixed {element} Data[{count}];");
        }
        else for (int i = 0; i < count; i++)
        {
            Documentation(Array.Empty<Token>());
            Line($"[global::System.Runtime.InteropServices.FieldOffset({checked(i * elementStorage.Size)})]");
            EmitScalarMarshal(element);
            Line($"public {element} _element{i};");
        }
        Close();
        if (rootArray && fixedPrimitive && field.Api.ManagedAccess == "private" && field.Parent is StructDescriptor owner)
        {
            string read = AutomaticFieldConverters.BufferMethod(field, false), write = AutomaticFieldConverters.BufferMethod(field, true);
            if (!names.Add(read) || !names.Add(write) || owner.Declarations.Any(d => d.Name.text == read || d.Name.text == write))
                Error(field, "Generated fixed-buffer access helper collides with a declared member.");
            string ownerName = HandleNetCS.ManagedName(owner), member = Id(field.Name.text);
            Line($"internal static unsafe {element} {read}(in {ownerName} value, int index) {{ if ((uint)index >= {count}U) throw new global::System.ArgumentOutOfRangeException(nameof(index)); fixed ({element}* data = value.{member}.Data) return data[index]; }}");
            Line($"internal static unsafe void {write}(ref {ownerName} value, int index, {element} input) {{ if ((uint)index >= {count}U) throw new global::System.ArgumentOutOfRangeException(nameof(index)); fixed ({element}* data = value.{member}.Data) data[index] = input; }}");
        }
        Note(field, "Array storage uses explicit size/offsets and embedded fixed storage; managed address alignment is not guaranteed by Pack.");
        return Id(name);
    }
    void EmitLayout(NativeStorage storage) => Line($"[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Explicit, Size = {storage.Size}, Pack = {storage.Alignment}, CharSet = global::System.Runtime.InteropServices.CharSet.Unicode)]");
    void EmitScalarMarshal(string type)
    {
        if (type == "bool") Line("[global::System.Runtime.InteropServices.MarshalAs(global::System.Runtime.InteropServices.UnmanagedType.U1)]");
        if (type == "char") Line("[global::System.Runtime.InteropServices.MarshalAs(global::System.Runtime.InteropServices.UnmanagedType.U2)]");
    }
    void Documentation(DeclarationDescriptor declaration)
    {
        var header = declaration.HeaderTokens.AsEnumerable();
        if (declaration is FieldDescriptor field) header = header.Concat(field.TypeTokens);
        var first = header.Where(t => !t.IsTrivia).OrderBy(t => t.line).ThenBy(t => t.col).FirstOrDefault();
        if (string.IsNullOrEmpty(first.text)) first = declaration.Name;
        int index = sourceTokens.FindIndex(t => t.line == first.line && t.col == first.col && t.text == first.text);
        List<Token> comments = [];
        for (int i = index - 1; i >= 0 && sourceTokens[i].IsTrivia; --i)
        {
            if (sourceTokens[i].kind != Token.Kind.Comment) continue;
            int previous = i - 1;
            while (previous >= 0 && sourceTokens[previous].IsTrivia) previous--;
            // A trailing comment belongs to the preceding declaration.
            if (previous >= 0 && sourceTokens[previous].line == sourceTokens[i].line) continue;
            comments.Insert(0, sourceTokens[i]);
        }
        Documentation(comments);
    }

    void Documentation(IEnumerable<Token> comments)
    {
        List<string> lines = [];
        foreach (var token in comments)
        {
            string text = token.text;
            if (text.StartsWith("//")) text = text.TrimStart('/').TrimStart();
            else if (text.StartsWith("/*")) text = text.EndsWith("*/") ? text[2..^2] : text[2..];
            foreach (string line in text.Replace("\r", "").Split('\n'))
                lines.Add(line.Trim().TrimStart('*').TrimStart());
        }
        if (!lines.Any(l => l.Length != 0)) lines = ["TODO: comment this one"];
        // Preserve existing XML documentation; escape ordinary C++ prose.
        if (lines.Any(l => l.TrimStart().StartsWith("<summary>")))
        {
            foreach (string line in lines) Line("/// " + line);
            return;
        }
        Line("/// <summary>");
        foreach (string line in lines)
            Line("/// " + line.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;"));
        Line("/// </summary>");
    }

    static string AttributePrefix(DeclarationDescriptor declaration) => string.Concat(declaration.Api.ManagedAttributes.Distinct(StringComparer.Ordinal).Select(value => "[" + value + "] "));
    void EmitAttributes(DeclarationDescriptor declaration)
    {
        foreach (string value in declaration.Api.ManagedAttributes.Distinct(StringComparer.Ordinal)) Line("[" + value + "]");
    }

    void EmitDeprecated(IEnumerable<Token> tokens)
    {
        var values = tokens.Where(token => !token.IsTrivia).ToList();
        int at = values.FindIndex(t => t == "deprecated" || declarationMacros.TryGetValue(t.text, out var kind) && kind == DeclarationMacroKind.Deprecated);
        if (at < 0) return;
        Token message = default;
        if (at + 1 < values.Count && values[at + 1] == "(")
        {
            int depth = 0;
            for (int i = at + 1; i < values.Count; i++)
            {
                if (values[i] == "(") depth++;
                else if (values[i] == ")" && --depth == 0) break;
                if (depth == 1 && values[i].kind == Token.Kind.String && message.text == null) message = values[i];
            }
        }
        Line(message.text?.StartsWith('"') == true ? "[global::System.Obsolete(" + message.text + ")]" : "[global::System.Obsolete]");
    }
    void Note(DeclarationDescriptor declaration, string message) => result.Notes.Add(new LogEntry(message,
        string.IsNullOrEmpty(declaration.Name.text) ? declaration.HeaderTokens.FirstOrDefault(t => !t.IsTrivia) : declaration.Name, LogEntryType.Warning, "VETCS002"));
    static string Access(DeclarationDescriptor declaration, bool nested) => declaration.Api.ManagedAccess ?? (!nested ? "public" : declaration.Access is "private" or "protected" ? declaration.Access : "public");
    internal static string Qualified(string name) => string.Join(".", name.Split("::", StringSplitOptions.RemoveEmptyEntries).Select(Id));
    static readonly HashSet<string> CSharpKeywords = new(StringComparer.Ordinal)
